import { test, expect } from "@playwright/test";
import { BlobWriter, TextReader, ZipWriter } from "@zip.js/zip.js";

test("bundled demo remains a separate offline entry after a custom archive", async ({ page, context }) => {
  await page.addInitScript(() => Object.defineProperty(navigator, "standalone", { get: () => true }));
  await page.goto("./");
  await expect(page.locator("#statusText")).toHaveText("Приложение готово к импорту");
  const demo = page.locator('[data-archive-id="builtin-demo"]');
  await expect(demo).toBeVisible();
  const writer = new ZipWriter(new BlobWriter("application/zip"));
  await writer.add("index.html", new TextReader("<!doctype html><h1>custom-site-marker</h1>"));
  const buffer = Buffer.from(await (await writer.close()).arrayBuffer());
  page.on("dialog", dialog => dialog.accept());
  const chooser = page.waitForEvent("filechooser");
  await page.locator("#chooseArchiveButton").click();
  await (await chooser).setFiles({ name: "custom-site.zip", mimeType: "application/zip", buffer });
  await expect(page.locator("#statusText")).toHaveText("Сайт готов к автономной работе");
  const custom = page.locator('.archive-entry').filter({ has: page.locator('h3', { hasText: 'custom-site.zip' }) });
  await context.setOffline(true);
  await page.reload();
  await expect(page.locator("#viewer")).toBeVisible();
  await page.locator("#viewerClose").click();
  await demo.locator('[data-archive-action="open"]').click();
  await expect(page.locator("#infoArchive")).toHaveText("Встроенный демо-сайт (demo.7z)", { timeout: 90_000 });
  await expect(page.locator("#viewer")).toBeVisible();
  expect(await page.evaluate(async () => (await fetch("./__gamespace_content__/games/tictac/game.html")).ok)).toBe(true);
  await page.locator("#viewerClose").click();
  await expect(page.locator(".archive-entry")).toHaveCount(2);
  await custom.locator('[data-archive-action="open"]').click();
  await expect(page.frameLocator("#siteFrame").locator("h1")).toHaveText("custom-site-marker");
  await page.locator("#viewerClose").click();
  await demo.locator('[data-archive-action="remove"]').click();
  await expect(demo.locator('[data-archive-action="open"]')).toHaveText("Подготовить и открыть");
  await expect(custom).toBeVisible();
  await demo.locator('[data-archive-action="open"]').click();
  await expect(page.locator("#viewer")).toBeVisible();
  await expect(page.locator("#errorPanel")).toBeHidden();
});
